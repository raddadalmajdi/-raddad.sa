import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import dotenv from 'dotenv';

const root = process.cwd();
const envPath = resolve(root, '.env');

if (existsSync(envPath)) {
    dotenv.config({ path: envPath });
}

const config = {
    apiKey: process.env.VITE_FIREBASE_API_KEY || 'YOUR_API_KEY',
    authDomain: process.env.VITE_FIREBASE_AUTH_DOMAIN || 'YOUR_PROJECT_ID.firebaseapp.com',
    projectId: process.env.VITE_FIREBASE_PROJECT_ID || 'YOUR_PROJECT_ID',
    storageBucket: process.env.VITE_FIREBASE_STORAGE_BUCKET || 'YOUR_PROJECT_ID.appspot.com',
    messagingSenderId: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || 'YOUR_MESSAGING_SENDER_ID',
    appId: process.env.VITE_FIREBASE_APP_ID || 'YOUR_APP_ID',
};

const adminEmails = (process.env.VITE_FIREBASE_ADMIN_EMAILS || 'raddad@raddad.sa')
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean);

const output = `// Generated by scripts/generate-firebase-config.mjs — edit .env then run: npm run build
window.firebaseConfig = ${JSON.stringify(config, null, 4)};
window.firebaseConfig.adminEmails = ${JSON.stringify(adminEmails, null, 4)};
`;

writeFileSync(resolve(root, 'js/firebase-config.js'), output, 'utf8');

const ready = config.apiKey !== 'YOUR_API_KEY' && config.projectId !== 'YOUR_PROJECT_ID';
console.log(ready ? 'Firebase config generated from .env' : 'Firebase config generated with placeholders (fill .env)');
